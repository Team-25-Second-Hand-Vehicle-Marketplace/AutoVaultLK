import http from 'k6/http';
import { check, sleep } from 'k6';
import { Trend } from 'k6/metrics';
import encoding from 'k6/encoding';
import { textSummary } from 'https://jslib.k6.io/k6-summary/0.1.0/index.js';

/**
 * Volume test: the Test Plan's own named scenario (§3.3.5) - "ingestion of
 * progressively larger CSV/ZIP source files and record counts to establish
 * the practical per-job ceiling and confirm chunking and concurrency
 * control hold at scale." This is NOT about concurrent users (that is the
 * end-to-end-load.js scenario, and its own multi-dealer extension) - this
 * is ONE dealer, ONE upload at a time, with the FILE getting bigger each
 * step, run sequentially so each size's completion time is attributable to
 * that size alone rather than to competing uploads.
 *
 * Files are pre-generated by ingestion-service's own vehicle-generator
 * tool (src/tools/vehicle-generator/vehicle-generator.ts - the Readme
 * documents up to a 10000-row CSV as a known, supported size), not
 * constructed inline: k6's JS runtime has no reason to duplicate that
 * generator's logic, and using the project's own real tool is closer to
 * how a dealer's actual large export would look than a synthetic
 * repeated-row pattern would be.
 *
 * Each pre-generated file's registration_number column is deliberately
 * NOT unique across separate generator runs (vehicle-generator.ts's
 * generateRegistration() returns WP-0001, WP-0002... starting from 1 in
 * EVERY file) - confirmed by inspection before this script was written,
 * having already been bitten by exactly this collision once in
 * dealer-bulk-upload.spec.ts (Playwright). Rather than regenerating fixed
 * files per run, this script rewrites the registration_number column with
 * a run-unique prefix in memory before upload, so re-running this script
 * against the same shared local/staging database never collides with a
 * prior run's rows.
 *
 * Requires the CSV fixtures to already exist - generate them first:
 *   cd ingestion-service
 *   npx tsx src/tools/vehicle-generator/vehicle-generator.ts --count 100   --format csv --mode clean --output test-data/k6-volume-100.csv
 *   npx tsx src/tools/vehicle-generator/vehicle-generator.ts --count 500   --format csv --mode clean --output test-data/k6-volume-500.csv
 *   npx tsx src/tools/vehicle-generator/vehicle-generator.ts --count 2000  --format csv --mode clean --output test-data/k6-volume-2000.csv
 *   npx tsx src/tools/vehicle-generator/vehicle-generator.ts --count 5000  --format csv --mode clean --output test-data/k6-volume-5000.csv
 *   npx tsx src/tools/vehicle-generator/vehicle-generator.ts --count 15000 --format csv --mode clean --output test-data/k6-volume-15000.csv
 *
 * (25MB is the backend's own CSV size cap - ingestion-upload.service.ts's
 * maxCsvSize - so file sizes here stay well under that; ~5000 rows is
 * roughly 420KB at this generator's average row width, leaving orders of
 * magnitude of headroom before the byte-size limit becomes the binding
 * constraint rather than processing time.)
 */

const AUTH_BASE_URL = __ENV.AUTH_BASE_URL || 'http://localhost:3001';
const INGESTION_BASE_URL = __ENV.INGESTION_BASE_URL || 'http://localhost:3003';
const ADMIN_BASE_URL = __ENV.ADMIN_BASE_URL || 'http://localhost:3004';
const ADMIN_EMAIL = __ENV.ADMIN_SEED_EMAIL;
const ADMIN_PASSWORD = __ENV.ADMIN_SEED_PASSWORD;

// open() must be called at init time (module scope), not inside a
// function - k6 reads the file from the local filesystem once, during
// script compilation, and bundles its content for every VU/iteration.
const VOLUME_SIZES = [100, 500, 2000, 5000, 15000];
// open() resolves relative to THIS FILE's own directory
// (performance/scripts/), confirmed by the exact error path a single ../
// produced on the first attempt: performance/ingestion-service/... - one
// level short. Two levels up reaches the repo root, then into
// ingestion-service/.
const CSV_FILES = VOLUME_SIZES.map((count) => ({
  count,
  content: open(`../../ingestion-service/test-data/k6-volume-${count}.csv`),
}));

export const options = {
  scenarios: {
    volume: {
      executor: 'shared-iterations',
      vus: 1,
      iterations: CSV_FILES.length,
      maxDuration: '15m', // generous ceiling across all sizes combined
    },
  },
  setupTimeout: '2m',
};

const DOCUMENT_PNG_BASE64 =
  'iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mNk+A8AAQUBAScY42YAAAAASUVORK5CYII=';

const jobCompletionTrend = new Trend('ingestion_job_completion_ms', true);

/** Rewrites the registration_number column with a run-unique prefix, keeping every other column untouched. */
function makeRegistrationNumbersUnique(csvContent, runStamp) {
  const lines = csvContent.trim().split('\n');
  const header = lines[0];
  const regColumnIndex = header.split(',').indexOf('registration_number');

  const rewritten = lines.slice(1).map((line, rowIndex) => {
    const cells = line.split(',');
    cells[regColumnIndex] = `K6VOL-${runStamp}-${rowIndex}`;
    return cells.join(',');
  });

  return [header, ...rewritten].join('\n') + '\n';
}

export function setup() {
  if (!ADMIN_EMAIL || !ADMIN_PASSWORD) {
    throw new Error(
      'setup: ADMIN_SEED_EMAIL / ADMIN_SEED_PASSWORD must be set in the environment running this script.',
    );
  }

  const stamp = Date.now();
  const email = `k6-volume-dealer-${stamp}@example.test`;
  const password = 'Passw0rd!23';

  const documentBytes = encoding.b64decode(DOCUMENT_PNG_BASE64);
  const uploadDocRes = http.post(`${AUTH_BASE_URL}/documents/verification`, {
    document: http.file(documentBytes, 'verification.png', 'image/png'),
  });
  if (uploadDocRes.status !== 201 && uploadDocRes.status !== 200) {
    throw new Error(`setup: document upload failed (status ${uploadDocRes.status})`);
  }
  const documentKey = JSON.parse(uploadDocRes.body).key;

  const registerRes = http.post(
    `${AUTH_BASE_URL}/auth/register/dealer`,
    JSON.stringify({
      email,
      password,
      name: 'k6 Volume Dealer',
      dealerType: 'business',
      businessRegistrationNumber: `PV ${stamp}`,
      businessAddress: '1 Test Road',
      city: 'Colombo',
      companyName: `k6 Volume Motors ${stamp}`,
      contactNumber: '+94771234567',
      verificationDocuments: { businessRegistrationCertificate: documentKey },
    }),
    { headers: { 'Content-Type': 'application/json' } },
  );
  if (registerRes.status !== 201) {
    throw new Error(`setup: dealer registration failed (status ${registerRes.status}): ${registerRes.body}`);
  }
  const registerBody = JSON.parse(registerRes.body);
  const dealerUserId = registerBody.user.id;

  const verifyRes = http.post(
    `${AUTH_BASE_URL}/auth/email/verify`,
    JSON.stringify({ token: registerBody.verificationToken }),
    { headers: { 'Content-Type': 'application/json' } },
  );
  if (verifyRes.status !== 200 && verifyRes.status !== 201) {
    throw new Error(`setup: email verification failed (status ${verifyRes.status})`);
  }

  const adminLoginRes = http.post(
    `${AUTH_BASE_URL}/auth/login/admin`,
    JSON.stringify({ email: ADMIN_EMAIL, password: ADMIN_PASSWORD }),
    { headers: { 'Content-Type': 'application/json' } },
  );
  if (adminLoginRes.status !== 200 && adminLoginRes.status !== 201) {
    throw new Error(`setup: admin login failed (status ${adminLoginRes.status})`);
  }
  const adminToken = JSON.parse(adminLoginRes.body).accessToken;

  const approveRes = http.post(
    `${ADMIN_BASE_URL}/admin/dealers/${dealerUserId}/approve`,
    null,
    { headers: { Authorization: `Bearer ${adminToken}` } },
  );
  if (approveRes.status !== 200 && approveRes.status !== 201) {
    throw new Error(`setup: dealer approval failed (status ${approveRes.status})`);
  }

  const dealerLoginRes = http.post(
    `${AUTH_BASE_URL}/auth/login`,
    JSON.stringify({ email, password }),
    { headers: { 'Content-Type': 'application/json' } },
  );
  if (dealerLoginRes.status !== 200 && dealerLoginRes.status !== 201) {
    throw new Error(`setup: dealer login failed (status ${dealerLoginRes.status})`);
  }

  return { dealerToken: JSON.parse(dealerLoginRes.body).accessToken, runStamp: stamp };
}

/**
 * shared-iterations with 1 VU and iterations === CSV_FILES.length: each
 * iteration processes exactly one file, in ascending size order (array
 * order), sequentially - the next size never starts until the previous
 * job reaches a terminal state, so each size's timing is attributable to
 * that size alone, not to overlap with the previous upload still running.
 */
export default function (data) {
  const file = CSV_FILES[__ITER];
  const csv = makeRegistrationNumbersUnique(file.content, `${data.runStamp}-${__ITER}`);

  const uploadStart = Date.now();
  const uploadRes = http.post(
    `${INGESTION_BASE_URL}/ingest/upload`,
    { csv: http.file(csv, `inventory-${file.count}.csv`, 'text/csv') },
    {
      headers: { Authorization: `Bearer ${data.dealerToken}` },
      tags: { name: 'ingest_upload', size: String(file.count) },
      timeout: '60s', // a 15000-row multipart upload needs more than k6's 30s default
    },
  );
  check(uploadRes, { 'upload accepted (202)': (r) => r.status === 202 });
  if (uploadRes.status !== 202) {
    throw new Error(
      `volume[${file.count} rows]: upload failed (status ${uploadRes.status}): ${uploadRes.body}`,
    );
  }
  const jobId = JSON.parse(uploadRes.body).jobId;

  let status = 'PENDING';
  let pollCount = 0;
  // Larger files legitimately need more polling time - scaled roughly to
  // size rather than one fixed ceiling for every row count.
  const maxPolls = Math.max(30, Math.ceil(file.count / 100));
  while (!['COMPLETED', 'PARTIAL', 'FAILED'].includes(status) && pollCount < maxPolls) {
    sleep(2);
    const statusRes = http.get(`${INGESTION_BASE_URL}/jobs/${jobId}`, {
      headers: { Authorization: `Bearer ${data.dealerToken}` },
      tags: { name: 'job_status_poll' },
    });
    if (statusRes.status === 200) status = JSON.parse(statusRes.body).status;
    pollCount += 1;
  }

  const completionMs = Date.now() - uploadStart;
  jobCompletionTrend.add(completionMs, { size: String(file.count) });

  check(status, {
    [`${file.count}-row job reached a terminal, non-FAILED state`]: (s) =>
      s === 'COMPLETED' || s === 'PARTIAL',
  });

  console.log(
    `volume[${file.count} rows]: job ${jobId} reached ${status} in ` +
      `${(completionMs / 1000).toFixed(1)}s (${pollCount} polls, ` +
      `${(completionMs / file.count).toFixed(1)}ms/row)`,
  );
}

export function handleSummary(data) {
  const totalRequests = data.metrics.http_reqs ? data.metrics.http_reqs.values.count : 0;
  if (totalRequests === 0) {
    throw new Error(
      'dealer-ingestion-volume made zero HTTP requests - every step threw before any request ' +
        'fired (check the k6 error log above, setup(), and that the CSV fixtures exist).',
    );
  }
  return { stdout: textSummary(data, { indent: ' ', enableColors: true }) };
}
